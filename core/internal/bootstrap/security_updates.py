# STRUCTURE: ▶ ensure ┌pkg installed?┐ → ◇ no → install_apt_packages(unattended-upgrades) → ◇ write 20auto-upgrades (content-match no-op) → ◇ write 50unattended-upgrades (origins security-only, reboot policy) → ⎋ bool
