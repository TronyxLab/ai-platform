## @purpose  Рендер pyproject.toml (ruff + pytest конфиг). ТОЛЬКО для python-языков
##           (python|backend); иначе возвращает "" (файл не генерируется).
##           BASELINE: ruff format (стиль), ruff check отключён (select = [] — агент не
##           гоняется по правкам, §3.4). FULL: полный набор правил + strict-pytest.
## @io       ⇥ project_name: str, language: str, level: str → ⎋ str ("" если language не python)
## @complexity O(1)
## @invariants
##   - baseline: select = [] (явно пусто — детект); addopts = "-q -x --timeout=60"
##   - full: select = RUFF_FULL_SELECT; ignore = RUFF_FULL_IGNORE;
##     addopts = "-q -x --timeout=60 --strict-markers --strict-config"
##   - line-length 120, target py312, quote-style double (всегда — стиль дешёвый)
def render_pyproject(project_name: str, language: str, level: str) -> str:
    """Render pyproject.toml (ruff + pytest) for python projects; "" for non-python."""
    if language not in _PYTHON_TYPES:
        logger.info("[IMP:7][practices_gen][pyproject] language=%s — no pyproject rendered", language)
        return ""

    full = level == "full"
    select_line = (
        "select = [" + ", ".join(f'"{r}"' for r in RUFF_FULL_SELECT) + "]"
        if full
        else "select = []  # baseline: ruff check выключен (только format)"
    )
    ignore_line = (
        "ignore = [" + ", ".join(f'"{r}"' for r in RUFF_FULL_IGNORE) + "]"
        if full
        else "# (baseline: ignore не нужен — select пуст)"
    )
    addopts = "-q -x --timeout=60" if not full else "-q -x --timeout=60 --strict-markers --strict-config"
    markers = "markers = []" if not full else 'markers = ["gate", "contract", "smoke"]'

    content = f"""{GENERATED_HEADER}
# Project: {project_name}
# Source: core/internal/practices/practices_manifest.yaml (pins: ruff_pre_commit)

[tool.ruff]
line-length = 120
target-version = "py312"

[tool.ruff.format]
quote-style = "double"            # всегда (стиль — дешёвый)

[tool.ruff.lint]
# BASELINE: ruff check НИЧЕГО не делает (только format).
# FULL: полный набор правил (см. RUFF_FULL_SELECT в generators.py).
{select_line}
{ignore_line}

[tool.pytest.ini_options]
# BASELINE: -q -x --timeout=60, allow_no_tests (мок без тестов не падает)
# FULL: + strict-markers, strict-config, filterwarnings=error
addopts = "{addopts}"
{markers}
"""
    logger.info(
        "[IMP:8][practices_gen][pyproject] rendered (language=%s level=%s, %d chars)", language, level, len(content)
    )
    return content


