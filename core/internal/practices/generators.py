# region FUNC_compute_generator_hash
## @purpose  Детерминированный hash отрендеренных GENERATED-файлов (DevPlan 137 §2.1B) —
##           drift-detect: sha256("v{version}:{level}\n" + Σ sorted "path=sha256(content)\n").
## @io       ⇥ files: dict[str, str] (path → content), version: int, level: str → ⎋ str "sha256:..."
## @complexity O(N * C) где N = число файлов, C = размер контента
## @invariants
##   - sorted(files) — детерминизм (порядок итерации не важен)
##   - Уровень входит в hash (baseline vs full конфиги различны)
def compute_generator_hash(files: dict[str, str], version: int, level: str) -> str:
    """Deterministic hash of rendered GENERATED files (drift-detect)."""
    h = hashlib.sha256()
    h.update(f"v{version}:{level}\n".encode())
    for path in sorted(files):  # sorted = детерминизм
        h.update(f"{path}={hashlib.sha256(files[path].encode()).hexdigest()}\n".encode())
    result = f"sha256:{h.hexdigest()}"
    logger.info(
        "[IMP:9][practices_gen][hash] generator_hash=%s (v%d, level=%s, %d files)", result, version, level, len(files)
    )
    return result


# endregion FUNC_compute_generator_hash


