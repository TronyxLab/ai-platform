from __future__ import annotations

import argparse
import logging
import sys
from datetime import datetime
from pathlib import Path

import yaml

logger = logging.getLogger(__name__)


def load_yaml(yaml_path: str) -> dict:
    """Load and validate platform-env.yaml."""
    path = Path(yaml_path)
    if not path.is_file():
        print(f"FAIL-FAST: platform-env.yaml not found: {yaml_path}", file=sys.stderr)
        sys.exit(1)
    try:
        with open(path) as f:
            data = yaml.safe_load(f)
    except yaml.YAMLError as e:
        print(f"FAIL-FAST: YAML parse error in {yaml_path}: {e}", file=sys.stderr)
        sys.exit(1)
    return data


def validate_provides(data: dict, profiles: list[str]) -> dict:
    """Validate provides keys are subset of profiles."""
    provides = data.get("provides", {})
    if not provides:
        print("FAIL-FAST: no provides: section found in platform-env.yaml", file=sys.stderr)
        sys.exit(1)
    profile_set = set(profiles)
    for svc_name in provides:
        if svc_name not in profile_set:
            print(f'FAIL-FAST: provides key "{svc_name}" is NOT in profiles list', file=sys.stderr)
            print(f"  Profiles: {profiles}", file=sys.stderr)
            sys.exit(1)
    return provides


def generate(data: dict, domain: str, project_name: str = "") -> list[str]:
    """Generate .env.platform lines from platform-env.yaml data.

    Args:
        data: Parsed platform-env.yaml dict
        domain: Platform domain
        project_name: Optional project name for DSN {NAME} substitution

    Returns:
        List of .env.platform lines
    """
    profiles = data.get("profiles", [])
    provides = validate_provides(data, profiles)
    proxy = data.get("proxy", {})

    lines: list[str] = []
    lines.append("# GENERATED by ai-platform — DO NOT EDIT")
    lines.append(f"# Generated: {datetime.now().isoformat()}")

    # PLATFORM_DOMAIN
    lines.append(f"PLATFORM_DOMAIN={domain}")

    # PLATFORM_PROVIDES
    provides_keys = sorted(provides.keys())
    lines.append(f"PLATFORM_PROVIDES={','.join(provides_keys)}")

    # Per-service HOST/PORT/DSN/URL
    for svc_name in sorted(provides.keys()):
        svc_upper = svc_name.upper()
        svc_data = provides[svc_name]

        host = svc_data.get("host", "")
        port = svc_data.get("port", "")
        dsn_tmpl = svc_data.get("dsn_template", "")
        url_tmpl = svc_data.get("url_template", "")

        if host:
            lines.append(f"PLATFORM_{svc_upper}_HOST={host}")
        if port:
            lines.append(f"PLATFORM_{svc_upper}_PORT={port}")

        # Substitute {NAME} in DSN template
        if dsn_tmpl:
            dsn_val = dsn_tmpl.replace("${NAME}", project_name) if project_name else dsn_tmpl
            lines.append(f"PLATFORM_{svc_upper}_DSN={dsn_val}")
        if url_tmpl:
            url_val = url_tmpl.replace("${NAME}", project_name) if project_name else url_tmpl
            url_val = url_val.replace("${DOMAIN}", domain)
            lines.append(f"PLATFORM_{svc_upper}_URL={url_val}")

    # Networks from provides — unique networks
    all_networks: set[str] = set()
    for svc_data in provides.values():
        for net in svc_data.get("networks", []):
            all_networks.add(net)
    for net in sorted(all_networks):
        net_upper = net.upper().replace("-", "_")
        lines.append(f"PLATFORM_{net_upper}={net}")

    # Proxy NO_PROXY
    no_proxy = proxy.get("no_proxy_internal", "")
    if no_proxy:
        lines.append(f"PLATFORM_NO_PROXY={no_proxy}")

    # Validation
    plat_count = sum(1 for line in lines if line.startswith("PLATFORM_"))
    if plat_count < 8:
        print(f"WARNING: Only {plat_count} PLATFORM_* variables generated (expected ≥8)", file=sys.stderr)

    logger.info("[IMP:9][gen_env_platform] Generation complete — %d PLATFORM_* variables", plat_count)
    return lines


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="[%(levelname)s][gen_env_platform] %(message)s", stream=sys.stderr)

    parser = argparse.ArgumentParser(description="Generate .env.platform from platform-env.yaml")
    parser.add_argument("--yaml", required=True, type=str, help="Path to platform-env.yaml")
    parser.add_argument("--name", type=str, default="", help="Project name for DSN substitution")
    parser.add_argument("--domain", type=str, default="ai-platform.local", help="Platform domain")
    args = parser.parse_args()

    data = load_yaml(args.yaml)
    lines = generate(data, domain=args.domain, project_name=args.name)
    for line in lines:
        print(line)

    logger.info("[IMP:9][gen_env_platform] CLI generation complete — %d lines written", len(lines))


if __name__ == "__main__":
    main()
