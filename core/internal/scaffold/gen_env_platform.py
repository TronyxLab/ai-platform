# region FUNC_load_yaml
## @purpose  Load and parse platform-env.yaml from disk.
##           Library-safe: raises FileNotFoundError or yaml.YAMLError instead of sys.exit().
## @param yaml_path  Path to platform-env.yaml on disk
## @return  Parsed YAML content as dict
## @raises FileNotFoundError  If yaml_path does not exist
## @raises yaml.YAMLError     If YAML content is malformed
def load_yaml(yaml_path: str) -> _PlatformEnvYaml:
    """Load and validate platform-env.yaml.

    Args:
        yaml_path: Path to platform-env.yaml on disk.

    Returns:
        Parsed YAML content as dict.

    Raises:
        FileNotFoundError: If yaml_path does not exist.
        yaml.YAMLError: If YAML content is malformed.
    """
    path = Path(yaml_path)
    if not path.is_file():
        msg = f"platform-env.yaml not found: {yaml_path}"
        raise FileNotFoundError(msg)
    with Path(path).open(encoding="utf-8") as f:
        # W11: yaml.safe_load returns Any → cast to platform-env boundary TypedDict
        data = cast(_PlatformEnvYaml, yaml.safe_load(f))
    logger.info("[IMP:8][load_yaml] Loaded YAML from %s", yaml_path)
    return data


# endregion FUNC_load_yaml


# ═══════════════════════════════════════════════════════════════════
# region FUNC_validate_provides
## @purpose  Validate that all provides: keys exist in profiles: list.
##           Library-safe: raises GenEnvPlatformValidationError instead of sys.exit().
## @param data      Parsed platform-env.yaml dict
## @param profiles  List of valid profile names from data
## @return  Validated provides dict (from data["provides"])
## @raises GenEnvPlatformValidationError  If provides section missing or key not in profiles
def validate_provides(data: _PlatformEnvYaml, profiles: list[str]) -> dict[str, _ProvidesEntry]:
    """Validate provides keys are subset of profiles.

    Args:
        data: Parsed platform-env.yaml dict.
        profiles: List of valid profile names.

    Returns:
        Validated provides dict from data["provides"].

    Raises:
        GenEnvPlatformValidationError: If provides section is missing
            or any provides key is not found in profiles.
    """
    provides = data.get("provides", {})
    if not provides:
        msg = "no provides: section found in platform-env.yaml"
        raise GenEnvPlatformValidationError(msg)
    profile_set = set(profiles)
    for svc_name in provides:
        if svc_name not in profile_set:
            msg = f'provides key "{svc_name}" is NOT in profiles list. Profiles: {profiles}'
            raise GenEnvPlatformValidationError(msg)
    logger.info("[IMP:9][validate_provides] Validated %d provide(s) against profiles", len(provides))
    return provides


# endregion FUNC_validate_provides


# ═══════════════════════════════════════════════════════════════════
# region FUNC_apply_credentials_to_dsn
## @purpose  Password-injection (DevPlan 133 W2.3/D4): подстановка реальных credentials
##           (из .platform-db.env) в DSN-шаблон. Заменяет ${NAME}_user/${NAME}_db на
##           фактические роль/БД (если заданы) и '***' на реальный пароль.
##           Без credentials → шаблон возвращается без изменений (обратная совместимость).
## @param dsn_tmpl     DSN template из platform-env.yaml (postgres-сервис: DSN вида
##                     postgresql://NAME_user:***\@pgbouncer:6432/NAME_db)
## @param project_name Project name (${NAME} подстановка — если credentials не покрывают)
## @param credentials  dict из .platform-db.env (PLATFORM_POSTGRES_DB/USER/PASSWORD) | None
## @return  str — DSN с подставленными credentials
## @complexity O(1)
## @invariants
##   - token_urlsafe(24) пароль не требует URL-экранирования (charset [A-Za-z0-9_-])
##   - Порядок: ${NAME}_user/${NAME}_db ДО ${NAME} (частичные совпадения не ломаются)
##   - '***' заменяется ТОЛЬКО при наличии пароля в credentials
def _apply_credentials_to_dsn(dsn_tmpl: str, project_name: str, credentials: dict[str, str] | None) -> str:
    """Substitute real DB credentials into a DSN template (password-injection, DevPlan 133)."""
    result = dsn_tmpl
    if credentials:
        user = credentials.get("PLATFORM_POSTGRES_USER", "") or ""
        db = credentials.get("PLATFORM_POSTGRES_DB", "") or ""
        pw = credentials.get("PLATFORM_POSTGRES_PASSWORD", "") or ""
        if user:
            result = result.replace("${NAME}_user", user)
        if db:
            result = result.replace("${NAME}_db", db)
        if pw:
            result = result.replace("***", pw)
    if project_name:
        result = result.replace("${NAME}", project_name)
    return result


# endregion FUNC_apply_credentials_to_dsn


# ═══════════════════════════════════════════════════════════════════
# region FUNC_load_credentials
## @purpose  Load DB credentials from .platform-db.env (project_dir) или явного файла
##           (--credentials-file). Канонический парсер — shared/secrets_env_parser.
##           Файл отсутствует → {} (без изменений поведения генератора).
## @param project_dir        Project directory (ищет dir/.platform-db.env)
## @param credentials_file   Explicit credentials file (приоритетнее project_dir)
## @return  dict[str, str] — {} если файла нет
## @complexity O(N) — N = строки файла
## @invariants
##   - Никогда не raise (отсутствие credentials-файла — нормальный режим)
##   - Значения маскируются в логах парсером (TRAP[BUG] 2026-08-03, секрет-лики)
def load_credentials(project_dir: str | None = None, credentials_file: str | None = None) -> dict[str, str]:
    """Load DB credentials from .platform-db.env ({} if file absent)."""
    from core.internal.shared.secrets_env_parser import parse

    path = ""
    if credentials_file:
        path = credentials_file
    elif project_dir:
        candidate = Path(project_dir) / ".platform-db.env"
        if candidate.is_file():
            path = str(candidate)
    if not path or not os.path.isfile(path):
        logger.info("[IMP:7][load_credentials] No credentials file at %s — DSN keeps '***'", path or "<none>")
        return {}
    try:
        creds = parse(path)
        logger.info(
            "[IMP:9][load_credentials] Credentials loaded from %s (%d key(s))",
            path,
            len(creds),
        )
    except (OSError, PlatformError, TypeError) as exc:  # noqa: EXC — graceful: битый credentials → без инъекции (best-effort)
        logger.warning("[IMP:7][load_credentials] Credentials parse skipped: %s", exc)
        return {}
    else:
        return creds


# endregion FUNC_load_credentials


# ═══════════════════════════════════════════════════════════════════
# region FUNC_generate
## @purpose  Generate .env.platform lines from parsed platform-env.yaml data dict.
##           Called by generate_env_platform() after load+validate.
## @param data          Parsed platform-env.yaml dict (must contain profiles/provides/proxy keys)
## @param domain        Platform domain (e.g. "ai-platform.local")
## @param project_name  Optional project name for ${NAME} substitution in DSN/URL templates
## @param credentials   Optional DB credentials dict (from .platform-db.env) — password-injection
## @return  List of .env.platform lines (newline-terminated)
## @raises GenEnvPlatformValidationError  If provides validation fails
def generate(
    data: _PlatformEnvYaml, domain: str, project_name: str = "", credentials: dict[str, str] | None = None
) -> list[str]:
    """Generate .env.platform lines from platform-env.yaml data.

    Args:
        data: Parsed platform-env.yaml dict.
        domain: Platform domain.
        project_name: Optional project name for DSN {NAME} substitution.
        credentials: Optional DB credentials (password-injection, DevPlan 133 W2).

    Returns:
        List of .env.platform lines.
    """
    profiles = data.get("profiles", [])
    provides = validate_provides(data, profiles)
    proxy = data.get("proxy", {})

    lines: list[str] = []
    lines.append("# GENERATED by ai-platform — DO NOT EDIT")
    lines.append(f"# Generated: {datetime.now(timezone.utc).isoformat()}")

    # PLATFORM_DOMAIN
    lines.append(f"PLATFORM_DOMAIN={domain}")

    # PLATFORM_PROVIDES
    provides_keys = sorted(provides.keys())
    lines.append(f"PLATFORM_PROVIDES={','.join(provides_keys)}")

    # Per-service HOST/PORT/DSN/URL
    for svc_name in sorted(provides.keys()):
        svc_upper = svc_name.upper()
        svc_data = provides[svc_name]

        host = svc_data.get("host", "")
        port = svc_data.get("port", "")
        dsn_tmpl = svc_data.get("dsn_template", "")
        url_tmpl = svc_data.get("url_template", "")

        if host:
            lines.append(f"PLATFORM_{svc_upper}_HOST={host}")
        if port:
            lines.append(f"PLATFORM_{svc_upper}_PORT={port}")

        # Substitute {NAME} in DSN template (credentials — password-injection, DevPlan 133 W2)
        if dsn_tmpl:
            dsn_val = _apply_credentials_to_dsn(dsn_tmpl, project_name, credentials)
            lines.append(f"PLATFORM_{svc_upper}_DSN={dsn_val}")
        if url_tmpl:
            url_val = url_tmpl.replace("${NAME}", project_name) if project_name else url_tmpl
            url_val = url_val.replace("${DOMAIN}", domain)
            lines.append(f"PLATFORM_{svc_upper}_URL={url_val}")

    # Networks from provides — unique networks
    all_networks: set[str] = set()
    for svc_data in provides.values():
        for net in svc_data.get("networks", []):
            all_networks.add(net)
    for net in sorted(all_networks):
        net_upper = net.upper().replace("-", "_")
        lines.append(f"PLATFORM_{net_upper}={net}")

    # Proxy NO_PROXY
    no_proxy = proxy.get("no_proxy_internal", "")
    if no_proxy:
        lines.append(f"PLATFORM_NO_PROXY={no_proxy}")

    # Validation
    plat_count = sum(1 for line in lines if line.startswith("PLATFORM_"))
    if plat_count < _PLATFORM_VARS_MIN:
        print(f"WARNING: Only {plat_count} PLATFORM_* variables generated (expected ≥8)", file=sys.stderr)

    logger.info("[IMP:9][gen_env_platform][generate] Generation complete — %d PLATFORM_* variables", plat_count)
    return lines


# endregion FUNC_generate


