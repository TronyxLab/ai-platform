## @purpose  Typed boundaries for platform-env.yaml (W11: yaml payload — no Any).
##           Provides-entries have optional host/port/dsn_template/url_template/networks.
class _ProvidesEntry(TypedDict, total=False):
    host: str
    port: int | str
    dsn_template: str
    url_template: str
    networks: list[str]


class _ProxyConfig(TypedDict, total=False):
    consumers: list[str]
    no_proxy_internal: str


class _PlatformEnvYamlBase(TypedDict, total=False):
    provides: dict[str, _ProvidesEntry]
    profiles: list[str]
    proxy: _ProxyConfig


class _PlatformEnvYaml(_PlatformEnvYamlBase):
    """Top-level platform-env.yaml (все секции опциональны — total=False база)."""


