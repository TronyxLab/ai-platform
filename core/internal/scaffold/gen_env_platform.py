## @purpose  CLI entry point. Parses args, calls generate_env_platform(), writes output.
##           Catches library exceptions and exits with code 1 + error message.
##           DI (DevPlan 167 D4): argv: list[str] | None = None — тесты вызывают main([...])
##           вместо monkeypatch-патча sys.argv (AF-4 main(argv) паттерн; None = sys.argv).
## @io       stdin: --yaml --domain --name args
##           stdout: .env.platform lines (unless --output specified)
##           stderr: LDD logs + error messages
## @exitcode 0  Success
## @exitcode 1  File not found, YAML parse error, or validation error
## 🧐 TRAP[DI-SEAM] · 2026-08-14 · — · CLI arg-flow тестируется реальным main(argv) + --output
## · Rejected: прямой вызов generate без проброса аргументов (тест патчил sys.argv +
## ·   gep.generate лямбдой — 3 monkeypatch.setattr на 2 сценария)
## · Reason: seam = тестируемость реального вызова main() с argv-инъекцией — 0 патчей,
## ·   тот же assert на потоке domain/project_name/credentials в generate
## · Rev: при появлении второго entrypoint-потребителя — вынести parse в отдельную функцию
def main(argv: list[str] | None = None) -> int:
    """CLI entry point for gen_env_platform.py.

    Wraps generate_env_platform() with CLI argument parsing and error
    handling. Exceptions from library functions are caught and printed
    to stderr; process exits with code 1.
    """
    logging.basicConfig(level=logging.INFO, format="[%(levelname)s][gen_env_platform] %(message)s", stream=sys.stderr)

    parser = argparse.ArgumentParser(description="Generate .env.platform from platform-env.yaml")
    parser.add_argument(
        "--yaml", type=str, default="", help="Path to platform-env.yaml (default: repo root via --project-dir)"
    )
    parser.add_argument("--name", type=str, default="", help="Project name for DSN substitution")
    parser.add_argument("--domain", type=str, default="", help="Platform domain")
    parser.add_argument("--output", type=str, default=None, help="Output path (default: stdout / project dir)")
    parser.add_argument(
        "--project-dir",
        type=str,
        default=None,
        help="Project directory: auto-resolve yaml/name/domain/output + credentials",
    )
    parser.add_argument(
        "--credentials-file", type=str, default=None, help="Explicit DB credentials file (.platform-db.env format)"
    )
    args = parser.parse_args(argv, namespace=_GenEnvArgs())

    # yaml_path инициализируется ДО try — except-ветка (yaml.YAMLError) читает его (reportPossiblyUnboundVariable)
    yaml_path: str = args.yaml
    # ruff: ignore[PLW0717] — тело try >5 операторов (длинный main-блок) — извлечение неразумно
    try:
        # ── --project-dir mode (DevPlan 133 W2.3): auto-resolve yaml/name/domain/output + credentials ──
        credentials: dict[str, str] | None = None
        output_path = args.output
        project_name = args.name
        domain = args.domain
        if args.project_dir:
            from core.internal.shared.project_yaml import get_domain, get_name, load_project_yaml

            proj_path = Path(args.project_dir)
            ai_data = load_project_yaml(proj_path)
            if not yaml_path:
                yaml_path = str(Path(__file__).resolve().parents[3] / "platform-env.yaml")
            if not project_name:
                project_name = get_name(ai_data) or proj_path.name
            if not domain:
                domain = get_domain(ai_data) or "ai-platform.local"
            if output_path is None:
                output_path = str(proj_path / ".env.platform")
            credentials = load_credentials(project_dir=args.project_dir, credentials_file=args.credentials_file)

        if not yaml_path:
            parser.error("--yaml is required (or use --project-dir)")
        if not domain:
            domain = "ai-platform.local"

        lines = generate_env_platform(yaml_path, domain=domain, project_name=project_name, credentials=credentials)
        if output_path:
            output_file = Path(output_path)
            output_file.parent.mkdir(parents=True, exist_ok=True)
            output_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
        else:
            for line in lines:
                print(line)
        logger.info("[IMP:9][gen_env_platform][main] CLI generation complete — %d lines written", len(lines))
    except FileNotFoundError as e:
        print(f"FAIL-FAST: {e}", file=sys.stderr)
        return 1
    except yaml.YAMLError as e:
        print(f"FAIL-FAST: YAML parse error in {yaml_path}: {e}", file=sys.stderr)
        return 1
    except GenEnvPlatformError as e:
        print(f"FAIL-FAST: {e}", file=sys.stderr)
        return 1
    return 0


# endregion FUNC_main


if __name__ == "__main__":
    sys.exit(main())
