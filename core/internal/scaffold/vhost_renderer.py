# region FUNC_render_vhost

# ⚠️ TRAP[BUG] · 2026-07-17 · DRIFT-1 · Flat directory (depth 1) required for vhost output
# · Symptom: vhost silently not loaded (fall-through to catch-all, class D12)
# · Root: producer wrote to conf.d/ subdir, non-recursive include overlay/*.conf
#   reads parent level — path mismatch → vhost never picked up
# · Fix: flat layout overlays/nginx/, no subdirectories
# · Prevention: static test verifies output path depth == 1 under overlays/nginx/


def render_vhost(
    entry: ProjectEntry,
    node: str,
    node_configs_dir: str,
    platform_domain: str | None = None,
    output_dir: str | None = None,
) -> VhostFile:
    """Render a single vhost file for a project entry.

    ▶ ┌entry + node + configs_dir┐ → ◇ resolve_cert_domain → ◇ generate_vhost_body
    → ◇ compute_body_hash → ◇ generate_vhost_header → ⊕ write <fqdn>.conf → ⎋ VhostFile

    ## @purpose — Full vhost generation pipeline for one project.
    ## @io — ⇥ entry: ProjectEntry — project name and domain
    ##       ⇥ node: str — target node name
    ##       ⇥ node_configs_dir: str — path to node-configs directory
    ##       ⇥ platform_domain: str | None — platform wildcard domain (optional)
    ##       ⇥ output_dir: str | None — override output directory (default: <node-configs>/<node>/overlays/nginx)
    ##       → ⎋ VhostFile — rendered vhost metadata
    ## @complexity — O(S) where S = template size
    ## @invariants
    ##   - Output is always <fqdn>.conf (flat directory, no subdirs — DRIFT-1)
    ##   - Body hash is computed BEFORE header prepends
    ##   - Header includes project source, domain, node, content-hash
    """
    fqdn = entry.domain.lower()
    cert_domain = resolve_cert_domain(fqdn, platform_domain)

    # Generate body first to compute hash (before header prepends)
    body = generate_vhost_body(fqdn, entry.name, cert_domain)
    body_hash = compute_body_hash(body)

    # Generate complete file: header + body
    header = generate_vhost_header(entry.name, fqdn, node, body_hash)
    full_content = header + body

    # Determine output path
    vhost_dir = Path(output_dir) if output_dir else Path(node_configs_dir) / node / "overlays" / "nginx"

    vhost_dir.mkdir(parents=True, exist_ok=True)
    vhost_path = vhost_dir / f"{fqdn}.conf"

    # Write to file
    vhost_path.write_text(full_content, encoding="utf-8")

    logger.info(
        "[IMP:9][render_vhost] Rendered: %s → %s (cert=%s, hash=%s...)",
        entry.name,
        vhost_path,
        cert_domain,
        body_hash[:12],
    )

    return VhostFile(
        path=str(vhost_path),
        fqdn=fqdn,
        project_name=entry.name,
        body_hash=body_hash,
    )


# endregion FUNC_render_vhost


