def check_duplicate_domains(entries: list[ProjectEntry]) -> None:
    """Check FQDN uniqueness across projects.

    ▶ ┌list[ProjectEntry]┐ → ○ set-based dict: domain → name → ◇ dup found?
    → ⊕ DuplicateDomainError | ⎋ None (PASS)

    ## @purpose — Enforce FQDN uniqueness: each domain must be claimed by exactly
    ##            one project. Replaces validate.sh --check-fqdn and inline python3 -c.
    ## @io — ⇥ entries: list[ProjectEntry] — projects with domains
    ##       → ⊕ DuplicateDomainError on duplicate | ⎋ None on pass
    ## @complexity — O(N) where N = entry count (dict-based dedup)
    ## @invariants
    ##   - Duplicate domain → DuplicateDomainError with details
    ##   - No duplicates → returns None (PASS)
    ##   - Empty list → returns None (trivially PASS)
    """
    seen: dict[str, str] = {}
    for entry in entries:
        domain = entry.domain.lower()
        if domain in seen:
            msg = f"Duplicate domain {domain} in projects: {seen[domain]} and {entry.name}"
            logger.error("[IMP:10][check_duplicate_domains] %s", msg)
            raise DuplicateDomainError(msg)
        seen[domain] = entry.name

    logger.info("[IMP:9][check_duplicate_domains] FQDN uniqueness check PASS (%d domains)", len(entries))


# endregion FUNC_check_duplicate_domains


