# region FUNC_compute_body_hash

# ⚠️ TRAP[BUG] · 2026-07-20 · P1 · || chain with pipefail evaluates ALL branches (compute_body_hash fallback)
# · Symptom: sha256sum AND shasum both output hash → body_hash=hash\\nhash (129 chars)
# · Root: A && B || C && D || E — || does NOT short-circuit under set -o pipefail
# · Fix: delegation to Python hashlib (SHA-256) — shell pipefail irrelevant
# · Prevention: hashlib.sha256() is single source of truth for string hashing


def compute_body_hash(content: str) -> str:
    """Compute SHA-256 hex digest of vhost body content.

    ▶ ┌content str┐ → ⊕ hashlib.sha256(content.encode()) → ⎋ hexdigest (64-char)

    ## @purpose — Deterministic content hash for drift detection (R6).
    ##            Uses same algorithm (SHA-256) as core.internal.shared.content_hash.
    ## @io — ⇥ content: str — vhost body content (without GENERATED header)
    ##       → ⎋ str — 64-char hex SHA-256 digest
    ## @complexity — O(N) where N = content size
    ## @invariants
    ##   - Same input → same output (deterministic)
    ##   - Uses SHA-256 via hashlib (cross-platform, deterministic)
    ##   - Content is the body text before header is prepended
    """
    digest = hashlib.sha256(content.encode("utf-8")).hexdigest()
    logger.debug("[IMP:6][compute_body_hash] Hash: %s...", digest[:12])
    return digest


