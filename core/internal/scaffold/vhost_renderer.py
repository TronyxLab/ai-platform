def resolve_cert_domain(fqdn: str, platform_domain: str | None = None) -> str:
    """Determine cert domain for SSL certificate path.

    ▶ ┌fqdn + platform_domain┐ → ◇ fqdn ends with .<platform_domain>?
    → ⊕ platform_domain (wildcard) | ⎋ fqdn (personal cert)

    ## @purpose — Resolve cert path: subdomain of PLATFORM_DOMAIN → wildcard
    ##            cert (/etc/letsencrypt/live/<platform_domain>/), else personal
    ##            cert (/etc/letsencrypt/live/<fqdn>/).
    ## @io — ⇥ fqdn: str — full domain name
    ##       ⇥ platform_domain: str | None — platform wildcard domain (optional)
    ##       → ⎋ str — resolved cert domain
    ## @complexity — O(N) where N = fqdn length
    ## @invariants
    ##   - If platform_domain is None or empty → return fqdn (personal cert)
    ##   - If fqdn.endswith(f".{platform_domain}") → return platform_domain (wildcard)
    ##   - Otherwise → return fqdn (personal cert)
    """
    if platform_domain and fqdn.endswith(f".{platform_domain}"):
        logger.info(
            "[IMP:9][resolve_cert_domain] Wildcard cert domain: %s (subdomain of PLATFORM_DOMAIN)", platform_domain
        )
        return platform_domain

    logger.info("[IMP:9][resolve_cert_domain] Personal cert domain: %s (own cert path)", fqdn)
    return fqdn


# endregion FUNC_resolve_cert_domain


