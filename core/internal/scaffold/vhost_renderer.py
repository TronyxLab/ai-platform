def generate_vhost_body(fqdn: str, project_name: str, cert_domain: str) -> str:
    """Generate nginx vhost config body (without GENERATED header).

    ▶ ┌{fqdn, project_name, cert_domain}┐ → ⊕ multi-line f-string nginx config
    → ◇ HTTP redirect (80) ◇ HTTPS server (443 ssl, http2) → ⎋ str

    ## @purpose — Generate nginx server block body using Python f-strings.
    ##            HTTP redirect on port 80, HTTPS on 443 with ssl_certificate paths,
    ##            Docker DNS resolver (127.0.0.11), security headers include,
    ##            rate limiting, proxy buffering, lazy DNS resolution via variable proxy_pass.
    ## @io — ⇥ fqdn: str — full domain name
    ##       ⇥ project_name: str — upstream service name
    ##       ⇥ cert_domain: str — resolved cert domain (from resolve_cert_domain)
    ##       → ⎋ str — nginx config body (without GENERATED header)
    ## @complexity — O(1) — fixed template
    ## @invariants
    ##   - $host, $request_uri, $upstream_xxx, $remote_addr, $scheme — nginx runtime vars
    ##     (NOT substituted — nginx resolves them at request time)
    ##   - {fqdn}, {project_name}, {cert_domain}, {nginx_safe_name} — compile-time values
    ##   - http2 on; on separate line (not deprecated listen ... http2 syntax)
    ##   - resolver 127.0.0.11 valid=30s for lazy Docker DNS resolution
    ##   - security-headers.conf included from /etc/nginx/includes/
    """
    nginx_safe_name = project_name.replace("-", "_")

    # NOTE: In this f-string, $host, $request_uri, $proxy_add_x_forwarded_for, etc.
    # are nginx runtime variables — they are literal $ in the output (not Python-
    # substituted). Only {fqdn}, {project_name}, {cert_domain}, {nginx_safe_name}
    # are compile-time substitutions via f-string interpolation.

    body = f"""# HTTP → HTTPS redirect
server {{
    listen 80;
    listen [::]:80;
    server_name {fqdn};

    location /.well-known/acme-challenge/ {{
        root /var/www/acme;
    }}

    location / {{
        return 301 https://$host$request_uri;
    }}
}}

# HTTPS vhost
server {{
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name {fqdn};

    http2 on;

    ssl_certificate /etc/letsencrypt/live/{cert_domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{cert_domain}/privkey.pem;

    # Docker DNS resolver with caching (30s TTL) — enables lazy DNS resolution
    # @rationale nginx resolves upstream hostnames at config load time by default.
    #   Using resolver 127.0.0.11 (Docker embedded DNS) + variables in proxy_pass
    #   defers resolution to request time. This allows nginx to start even when
    #   upstream containers are not ready, and to automatically pick up new IPs
    #   after force-recreate (TTL 30s).
    resolver 127.0.0.11 valid=30s ipv6=off;

    # ── Security headers (platform policy) ─────────────────────────────────
    include /etc/nginx/includes/security-headers.conf;

    # ── Rate limiting (dynamic zone: 10 r/s, burst 20) ─────────────────────
    limit_req zone=dynamic burst=20 nodelay;
    limit_req_status 429;

    # ── Buffering (platform policy) ────────────────────────────────────────
    proxy_buffering on;
    proxy_buffer_size 4k;
    proxy_buffers 8 4k;
    proxy_busy_buffers_size 8k;

    # ── Graceful degradation (S4 DevPlan 019) ────────────────────────────
    # Global resolver (127.0.0.11 valid=30s) in nginx.conf http-block + variable
    # proxy_pass provides lazy DNS resolution. If upstream container is not running,
    # nginx starts successfully and returns 502 on request (graceful degradation).
    # No need for upstream containers to exist at nginx startup.
    location / {{
        # Lazy DNS resolution via variable
        set $upstream_{nginx_safe_name} http://{project_name}:80;
        proxy_pass $upstream_{nginx_safe_name};
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        # Timeouts
        proxy_connect_timeout 10s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
    }}

    location /health {{
        proxy_pass $upstream_{nginx_safe_name}/health;
        access_log off;
    }}
}}
"""
    logger.info("[IMP:9][generate_vhost_body] Generated vhost body for %s (cert=%s)", fqdn, cert_domain)
    return body


