def remove_vhost(project_name: str, overlays_dir: str, platform_root: str | None = None) -> bool:
    """Remove an existing nginx vhost config.

    ▶ ┌project_name + overlays_dir┐ → ◇ find .conf with matching name/fqdn
    → ◇ file exists? → ⊕ delete + write audit-log | ⎋ True (idempotent)

    ## @purpose — Idempotent removal of vhost overlay file. Deletes the .conf
    ##            file and optionally writes an audit log entry. Safe to call
    ##            multiple times (no-op if file already removed).
    ## @io — ⇥ project_name: str — name of the project to remove vhost for
    ##       ⇥ overlays_dir: str — path to overlays/nginx directory
    ##       ⇥ platform_root: str | None — platform root for audit log (optional)
    ##       → ⎋ bool — True on success (or idempotent skip)
    ## @complexity — O(F) where F = number of .conf files in overlays_dir
    ## @invariants
    ##   - Idempotent: no-op if .conf file does not exist
    ##   - Audit log written only on actual deletion (not on skip)
    ##   - No service restart, no cert cleanup
    """
    overlay_path = Path(overlays_dir)
    if not overlay_path.exists():
        logger.info("[IMP:8][remove_vhost] Overlay dir not found: %s — idempotent skip", overlays_dir)
        return True

    # Find vhost file for this project (match by project name or domain pattern)
    # Strategy: scan .conf files, parse GENERATED header for project name
    removed = False
    for conf_file in overlay_path.glob("*.conf"):
        if not conf_file.is_file():
            continue
        # Check if this conf belongs to our project
        content = conf_file.read_text(encoding="utf-8")
        if f"node.yaml#projects[{project_name}]" in content or f"Source: node.yaml#projects[{project_name}]" in content:
            conf_file.unlink()
            logger.info("[IMP:9][remove_vhost] Deleted vhost: %s", conf_file)
            removed = True

    if not removed:
        logger.info("[IMP:8][remove_vhost] No vhost found for project '%s' — idempotent skip", project_name)

    # Write audit log on actual removal
    if removed and platform_root:
        audit_dir = Path(platform_root) / "var" / "log"
        audit_dir.mkdir(parents=True, exist_ok=True)
        audit_log = audit_dir / "audit.log"
        from datetime import datetime, timezone

        timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        audit_line = f"[{timestamp}] [audit] [vhost:remove] project={project_name}\n"
        with open(audit_log, "a") as f:
            f.write(audit_line)
        logger.info("[IMP:8][remove_vhost] Audit log written: removed vhost for %s", project_name)

    return True


# endregion FUNC_remove_vhost


