import logging
import pathlib
import xml.etree.ElementTree as ET

import pytest

from tests.conftest import ldd_trajectory

_PROJECT_ROOT: pathlib.Path = pathlib.Path(__file__).resolve().parent.parent.parent
_USERS_D_DIR: pathlib.Path = _PROJECT_ROOT / "core" / "modules" / "clickhouse" / "config" / "users.d"

logger = logging.getLogger(__name__)

# Dev/test password patterns that are acceptable
_DEV_PASSWORD_PATTERNS = ["test-", "not-for-prod", "CHANGE_ME", "placeholder"]

# Files in users.d/ that are auto-generated by ClickHouse Docker entrypoint
# from CLICKHOUSE_PASSWORD env var — protected by .gitignore, not security-reviewed.
_AUTO_GENERATED_USERS_XML = {"default-user.xml"}


def _find_users_xmls() -> list[pathlib.Path]:
    """Find all users XML files in ClickHouse users.d directory,
    excluding auto-generated files (created by Docker entrypoint from env vars).

    ## @purpose — Glob core/modules/clickhouse/config/users.d/*.xml,
    ##            skip files that are auto-generated from CLICKHOUSE_PASSWORD.
    ## @io — ⎋ list[pathlib.Path] of XML files found (non-auto-generated)
    ## @complexity — O(N) where N = files in users.d directory
    ## @rationale — default-user.xml is created by ClickHouse Docker entrypoint
    ##              from CLICKHOUSE_PASSWORD env var. It contains ::/0 and
    ##              access_management=1 by design (local dev). Protected by .gitignore.
    ##              Security scanning should only apply to committed config files.
    """
    if not _USERS_D_DIR.is_dir():
        logger.warning("[IMP:7][_find_users_xmls] users.d directory not found: %s", _USERS_D_DIR)
        return []

    xml_files = sorted(_USERS_D_DIR.glob("*.xml"))
    # Filter out auto-generated files
    filtered = [f for f in xml_files if f.name not in _AUTO_GENERATED_USERS_XML]
    skipped = len(xml_files) - len(filtered)
    if skipped:
        logger.info(
            "[IMP:8][_find_users_xmls] Skipped %d auto-generated file(s): %s",
            skipped,
            [f.name for f in xml_files if f.name in _AUTO_GENERATED_USERS_XML],
        )
    logger.info("[IMP:8][_find_users_xmls] Found %d XML file(s) in %s (after exclusions)", len(filtered), _USERS_D_DIR)
    return filtered


def _is_dev_password(password_text: str) -> bool:
    """Check if a password text is a dev/test placeholder.

    ## @purpose — Heuristic: if password contains "test-" or "not-for-prod" or "CHANGE_ME"
    ##            it's considered a dev placeholder (warning, not fail).
    ## @io — ⇥ password_text → ⎋ bool: True if dev placeholder
    ## @complexity — O(1)
    """
    lower = password_text.lower()
    return any(pattern.lower() in lower for pattern in _DEV_PASSWORD_PATTERNS)


def _parse_xml_safe(xml_path: pathlib.Path) -> ET.Element | None:
    """Parse an XML file safely, returning root element or None on failure.

    ## @purpose — Wrapper around ET.parse with error handling.
    ## @io — ⇥ xml_path → ⎋ ET.Element | None
    ## @complexity — O(N) where N = XML file size
    """
    try:
        tree = ET.parse(xml_path)
        return tree.getroot()
    except ET.ParseError as e:
        logger.warning("[IMP:7][_parse_xml_safe] XML parse error in %s: %s", xml_path, e)
        return None


