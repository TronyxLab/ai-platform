## @purpose — Gate test A6: validate ClickHouse users.d/*.xml security configuration:
##            1. No literal passwords (dev/test placeholders allowed with CDATA heuristic)
##            2. No open networks (::/0, 0.0.0.0/0)
##            3. No access_management=1 in production configs
## @scope — Scans core/modules/clickhouse/config/users.d/*.xml using xml.etree.ElementTree.
##          Dev/test placeholders (CDATA containing "test-*-not-for-prod") are tolerated.
## @invariants
##   - Empty password tag (no text, no CDATA) = FAIL (no-password auth)
##   - Literal non-placeholder password = FAIL
##   - CDATA with "test-*-not-for-prod" or "CHANGE_ME" = IMP:7 warning, not FAIL
##   - ::/0 or 0.0.0.0/0 in <ip> elements = FAIL
##   - <access_management>1</access_management> = FAIL (bypasses password auth)
## @rationale — Post-refactoring audit C1: prevent committing production passwords to repo
