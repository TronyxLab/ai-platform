@pytest.mark.static_audit
@ldd_trajectory
def test_clickhouse_healthcheck_contract(caplog: pytest.LogCaptureFixture) -> None:
    """Verify clickhouse/healthcheck.sh follows the module healthcheck contract.

    ## @purpose — Per core/modules/AGENTS.md: every healthcheck.sh must source
    ##            ../../lib/healthcheck.sh (shared library) and have proper exit codes
    ##            (exit 0 = healthy, exit 1 = unhealthy).
    ## @io — ⇥ caplog → ⎋ None (asserts contract compliance)
    ## @complexity — O(1) — single file content check
    ## @invariants
    ##   - Must contain: source ... ../../lib/healthcheck.sh
    ##   - Must contain: exit 0 (healthy path)
    ##   - Must contain: exit 1 (unhealthy path)
    ##   - Must have: set -euo pipefail (strict bash mode)
    ## @scenario — AC-2: Healthcheck script follows module contract
    """
    if not os.path.isfile(HEALTHCHECK_PATH):
        logger.error("[IMP:9][clickhouse-healthcheck] FAIL: healthcheck.sh not found at %s", HEALTHCHECK_PATH)
        pytest.fail(f"ClickHouse healthcheck.sh not found at {HEALTHCHECK_PATH}")

    with open(HEALTHCHECK_PATH, encoding="utf-8") as fh:
        content = fh.read()

    # ── Check: sources lib/healthcheck.sh ──
    sources_lib = "../../lib/healthcheck.sh" in content
    logger.info("[IMP:7][clickhouse-healthcheck] Sources lib/healthcheck.sh: %s", sources_lib)
    assert sources_lib, (
        "[IMP:9][clickhouse-healthcheck] FAIL: healthcheck.sh does not source ../../lib/healthcheck.sh — "
        "module contract violation (core/modules/AGENTS.md §Healthcheck-контракт)"
    )

    # ── Check: exit 0 (healthy path) ──
    has_exit_0 = "exit 0" in content
    logger.info("[IMP:7][clickhouse-healthcheck] Has exit 0 (healthy): %s", has_exit_0)
    assert has_exit_0, (
        "[IMP:9][clickhouse-healthcheck] FAIL: healthcheck.sh missing 'exit 0' — healthy path not defined"
    )

    # ── Check: exit 1 (unhealthy path) ──
    has_exit_1 = "exit 1" in content
    logger.info("[IMP:7][clickhouse-healthcheck] Has exit 1 (unhealthy): %s", has_exit_1)
    assert has_exit_1, (
        "[IMP:9][clickhouse-healthcheck] FAIL: healthcheck.sh missing 'exit 1' — unhealthy path not defined"
    )

    # ── Check: strict mode ──
    has_strict = "set -euo pipefail" in content
    logger.info("[IMP:7][clickhouse-healthcheck] Has 'set -euo pipefail': %s", has_strict)
    # Strict mode is recommended but not mandatory — log warning only
    if not has_strict:
        logger.warning("[IMP:8][clickhouse-healthcheck] WARN: healthcheck.sh missing 'set -euo pipefail'")

    # ── Check: docker exec based healthcheck (not systemctl — macOS compatible) ──
    has_docker_exec = "docker exec" in content
    logger.info("[IMP:7][clickhouse-healthcheck] Has 'docker exec': %s", has_docker_exec)
    assert has_docker_exec, (
        "[IMP:9][clickhouse-healthcheck] FAIL: healthcheck.sh missing 'docker exec' — "
        "must use docker exec for container healthcheck (macOS-compatible, no systemctl)"
    )

    logger.info("[IMP:9][clickhouse-healthcheck] PASS: Healthcheck contract satisfied")


