# Files in users.d/ that are auto-generated by ClickHouse Docker entrypoint
# and protected by .gitignore — should NOT be scanned for hardcoded passwords
# because they contain the env-var-derived password by design.
_AUTO_GENERATED_USERS_XML = {"default-user.xml"}


def _collect_xml_files(directory: str, exclude: set[str] | None = None) -> list[str]:
    """Collect all .xml files in a directory, sorted by name.

    ## @purpose — Find all XML config files for batch validation.
    ## @io — ⇥ directory: str, exclude: set[str] | None → ⎋ list[str] (absolute paths to .xml files)
    ## @complexity — O(N) where N = entries in directory
    """
    if not os.path.isdir(directory):
        return []
    exclude = exclude or set()
    return sorted(
        os.path.join(directory, f)
        for f in os.listdir(directory)
        if f.endswith(".xml") and os.path.isfile(os.path.join(directory, f)) and f not in exclude
    )


