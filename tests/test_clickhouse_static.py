# Test 1: XML config well-formedness
# ═══════════════════════════════════════════════════════════════════════════════


@pytest.mark.static_audit
@ldd_trajectory
def test_clickhouse_config_xml_valid(caplog: pytest.LogCaptureFixture) -> None:
    """Verify all ClickHouse config XML files (config.d/*.xml, users.d/*.xml) are well-formed.

    ## @purpose — Malformed XML in config.d or users.d causes ClickHouse to fail
    ##            silently (skips the fragment) or crash at startup. This test catches
    ##            XML syntax errors before Docker deployment.
    ## @io — ⇥ caplog → ⎋ None (asserts no XML parse errors)
    ## @complexity — O(N) where N = total XML files
    ## @scenario — AC-1: All XML configs parse without errors
    """
    xml_files = _collect_xml_files(CONFIG_D_DIR) + _collect_xml_files(USERS_D_DIR)

    if not xml_files:
        logger.warning("[IMP:7][clickhouse-xml] No XML config files found in config.d/ or users.d/")
        pytest.fail("No ClickHouse XML config files found — expected config.d/*.xml and users.d/*.xml")

    logger.info("[IMP:7][clickhouse-xml] Found %d XML config file(s)", len(xml_files))

    for xml_path in xml_files:
        try:
            ET.parse(xml_path)
            logger.info("[IMP:8][clickhouse-xml] Valid XML: %s", os.path.basename(xml_path))
        except ET.ParseError as exc:
            logger.error("[IMP:9][clickhouse-xml] FAIL: %s — XML parse error: %s", os.path.basename(xml_path), exc)
            pytest.fail(f"Malformed XML in {os.path.basename(xml_path)}: {exc}")

    logger.info("[IMP:9][clickhouse-xml] PASS: All %d XML config(s) well-formed", len(xml_files))


