# ═══════════════════════════════════════════════════════════════════════════════


@pytest.mark.static_audit
@ldd_trajectory
def test_clickhouse_users_xml_no_hardcoded_password(caplog: pytest.LogCaptureFixture) -> None:
    """Verify NO users.d/*.xml contains a hardcoded literal password.

    ## @purpose — Any literal <password>…</password> value in users.d/*.xml overrides
    ##            the CLICKHOUSE_PASSWORD env var, creating a security breach where
    ##            anyone on the Docker network can authenticate with full DDL rights.
    ##            This test scans ALL users.d/*.xml for any literal password content.
    ## @io — ⇥ caplog → ⎋ None (asserts no hardcoded password in any XML file)
    ## @complexity — O(N*M) where N = XML files, M = lines per file
    ## @invariants
    ##   - Scans ALL *.xml in USERS_D_DIR (not just 10-users.xml)
    ##   - Strips XML comments before scanning to avoid false positives from docs
    ##   - Detects ANY literal <password>…</password> content (not just empty tags)
    ##   - Also detects empty <password></password> and <password/> separately
    ## @scenario — AC-5: No hardcoded password in any users.d/*.xml
    """
    if not os.path.isdir(USERS_D_DIR):
        pytest.skip(f"Clickhouse users.d directory not found: {USERS_D_DIR}")

    # Exclude auto-generated files (default-user.xml is created by Docker entrypoint
    # from CLICKHOUSE_PASSWORD env var and is protected by .gitignore)
    xml_files = _collect_xml_files(USERS_D_DIR, exclude=_AUTO_GENERATED_USERS_XML)
    if not xml_files:
        logger.warning("[IMP:7][clickhouse-password] No trackable XML files in users.d/ (excluding auto-generated)")
        pytest.fail("No ClickHouse users.d/*.xml files found — expected at least 10-users.xml")

    logger.info(
        "[IMP:7][clickhouse-password] Scanning %d file(s) for hardcoded passwords: %s",
        len(xml_files),
        [os.path.basename(f) for f in xml_files],
    )

    # 💼 TRAP[BUSINESS] · 2026-07-12 · HI · No hardcoded password in users.d — security imperative
    # · Source: DevPlan C1 — ClickHouse security regression (post-refactoring audit)
    # · Risk: Hardcoded password overrides CLICKHOUSE_PASSWORD env var → authentication-less access

    any_violation = False

    for xml_path in xml_files:
        with open(xml_path, encoding="utf-8") as fh:
            content = fh.read()

        # Strip XML comments to avoid false positives from documentation
        xml_stripped = re.sub(r"<!--.*?-->", "", content, flags=re.DOTALL)

        # ── Check 1: empty password tag (<password></password> or <password/>) ──
        has_empty = "<password></password>" in xml_stripped or "<password/>" in xml_stripped
        if has_empty:
            any_violation = True
            logger.error(
                "[IMP:9][clickhouse-password] FAIL: %s contains empty <password> tag — "
                "this overrides CLICKHOUSE_PASSWORD env var.",
                os.path.basename(xml_path),
            )

        # ── Check 2: any literal password content in <password> element ──
        # Match <password> followed by anything that is NOT empty tag
        # Regex: <password[^>]*> followed by at least one non-whitespace char or CDATA
        has_literal = bool(re.search(r"<\s*password[^>]*>\s*(?:(?!<\s*/\s*password\s*>).)+", xml_stripped, re.DOTALL))
        if has_literal:
            any_violation = True
            # Extract the offending line for diagnostic
            for lineno, line in enumerate(content.splitlines(), 1):
                if re.search(r"<\s*password[^>]*>", line) and not re.search(r"<\s*password\s*/>", line):
                    logger.error(
                        "[IMP:9][clickhouse-password] FAIL: %s line %d — literal password content: %s",
                        os.path.basename(xml_path),
                        lineno,
                        line.strip(),
                    )

    # ── Check: does NOT restrict to 127.0.0.1 only (blocks Docker network access) ──
    # Use the sole 10-users.xml for this check
    sole_xml = os.path.join(USERS_D_DIR, "10-users.xml")
    if os.path.isfile(sole_xml):
        with open(sole_xml, encoding="utf-8") as fh:
            content_10 = fh.read()
        xml_stripped_10 = re.sub(r"<!--.*?-->", "", content_10, flags=re.DOTALL)
        has_localhost_only = all(
            ip_pat in xml_stripped_10 for ip_pat in ["<networks>", "<ip>127.0.0.1</ip>", "</networks>"]
        )
        if has_localhost_only:
            logger.warning(
                "[IMP:8][clickhouse-password] WARN: 10-users.xml restricts default user to 127.0.0.1 only. "
                "This blocks Grafana and Prometheus (on observability-net) from accessing ClickHouse. "
                "Remove <networks> restriction unless a separate user is created for Docker network access."
            )

    if any_violation:
        pytest.fail(
            "[IMP:9][clickhouse-password] FAIL: One or more users.d/*.xml files contain "
            "hardcoded passwords — see LDD log for details."
        )

    logger.info("[IMP:9][clickhouse-password] PASS: No hardcoded password in any users.d/*.xml (security guard)")
