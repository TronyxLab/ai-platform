@pytest.mark.static_audit
@ldd_trajectory
def test_clickhouse_module_yaml_structure(caplog: pytest.LogCaptureFixture) -> None:
    """Verify clickhouse/module.yaml has required fields and valid structure.

    ## @purpose — module.yaml is the machine-readable registry of module metadata.
    ##            deploy-modules.sh and CI gates read module.yaml to determine
    ##            install_type, dependencies, and network configuration.
    ##            Missing fields cause deploy failures.
    ## @io — ⇥ caplog → ⎋ None (asserts YAML structure)
    ## @complexity — O(1)
    ## @invariants
    ##   - D4 required keys: name, install_type, description, depends_on (core/modules/AGENTS.md)
    ##   - name must be 'clickhouse'
    ##   - install_type must be 'docker'
    ##   - depends_on must be a list (may be empty)
    ##   - spool_dir/spool_volume recommended (deploy-modules.sh)
    ##   - env_requires recommended (pre-deploy validation)
    ## @scenario — AC-3: Module YAML has complete and valid structure
    """
    if not os.path.isfile(MODULE_YAML_PATH):
        logger.error("[IMP:9][clickhouse-module-yaml] FAIL: module.yaml not found at %s", MODULE_YAML_PATH)
        pytest.fail(f"ClickHouse module.yaml not found at {MODULE_YAML_PATH}")

    with open(MODULE_YAML_PATH, encoding="utf-8") as fh:
        data = yaml.safe_load(fh)

    # version and config were removed from D4 contract per core/modules/AGENTS.md
    # D4 fields: name, install_type, description, depends_on, spool_dir, spool_volume,
    #            resources, env_shared, env_requires
    required_keys = {
        "name": str,
        "install_type": str,
        "description": str,
        "depends_on": list,
    }

    for key, expected_type in required_keys.items():
        assert key in data, f"[IMP:9][clickhouse-module-yaml] FAIL: module.yaml missing required key '{key}'"
        assert isinstance(data[key], expected_type), (
            f"[IMP:9][clickhouse-module-yaml] FAIL: module.yaml '{key}' expected {expected_type.__name__}, "
            f"got {type(data[key]).__name__}"
        )
        logger.info("[IMP:8][clickhouse-module-yaml] Key '%s' present with correct type", key)

    # ── Semantic assertions ──
    assert data["name"] == "clickhouse", (
        f"[IMP:9][clickhouse-module-yaml] FAIL: expected name='clickhouse', got '{data['name']}'"
    )
    assert data["install_type"] == "docker", (
        f"[IMP:9][clickhouse-module-yaml] FAIL: expected install_type='docker', got '{data['install_type']}'"
    )

    # spool_dir and spool_volume are D4-required (deploy-modules.sh consumes them)
    has_spool_dir = "spool_dir" in data and isinstance(data["spool_dir"], str)
    has_spool_volume = "spool_volume" in data and isinstance(data["spool_volume"], str)
    logger.info("[IMP:7][clickhouse-module-yaml] spool_dir: %s, spool_volume: %s", has_spool_dir, has_spool_volume)
    if not has_spool_dir:
        logger.warning("[IMP:8][clickhouse-module-yaml] WARN: module.yaml missing spool_dir (recommended)")
    if not has_spool_volume:
        logger.warning("[IMP:8][clickhouse-module-yaml] WARN: module.yaml missing spool_volume (recommended)")

    # env_requires is D4-required — ensures deploy catches missing secrets
    has_env_requires = "env_requires" in data and isinstance(data["env_requires"], list)
    logger.info("[IMP:7][clickhouse-module-yaml] env_requires: %s", has_env_requires)
    if has_env_requires:
        logger.info("[IMP:8][clickhouse-module-yaml] env_requires: %s", data["env_requires"])

    logger.info("[IMP:9][clickhouse-module-yaml] PASS: module.yaml structure valid")


