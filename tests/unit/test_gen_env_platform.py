# 🧪 TRAP[TEST] · Regression · CLI --yaml, --domain, --name arguments parse correctly
# · Scenario: Various combinations of CLI args → correct values in parsed namespace
# · Last fail: N/A (new test)
# · Remove if: argparse setup in main() changes
@ldd_trajectory
def test_cli_args(caplog, monkeypatch, tmp_path):
    """CLI --yaml, --domain, --name arguments should parse correctly via argparse."""
    yaml_path = tmp_path / "platform-env.yaml"
    data = {
        "profiles": ["test"],
        "provides": {"test": {"host": "test-host"}},
        "proxy": {},
    }
    with open(str(yaml_path), "w") as f:
        yaml.dump(data, f)

    # Track what generate() receives from main()
    captured = {}

    def mock_generate(data, domain, project_name=""):
        captured["domain"] = domain
        captured["project_name"] = project_name
        return [
            "# GENERATED by ai-platform — DO NOT EDIT",
            f"PLATFORM_DOMAIN={domain}",
        ]

    monkeypatch.setattr(gep, "generate", mock_generate)

    # Test all args provided
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "gen_env_platform.py",
            "--yaml",
            str(yaml_path),
            "--domain",
            "mydomain.com",
            "--name",
            "myapp",
        ],
    )

    with contextlib.suppress(SystemExit):
        gep.main()

    assert captured.get("domain") == "mydomain.com", f"Expected domain=mydomain.com, got {captured.get('domain')}"
    assert captured.get("project_name") == "myapp", f"Expected project_name=myapp, got {captured.get('project_name')}"

    logger.critical(
        "[IMP:9][test] CLI args parsed correctly: domain=%s, name=%s",
        captured.get("domain"),
        captured.get("project_name"),
    )


