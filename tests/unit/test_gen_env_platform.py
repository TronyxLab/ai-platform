# 🧪 TRAP[TEST] · Regression · generate() output matches contract structure
# · Scenario: Minimal platform-env.yaml with postgres+redis provides → header, PLATFORM_* vars, NO_PROXY
# · Last fail: N/A (new test)
# · Remove if: generate() logic changes
@ldd_trajectory
def test_generate_output_matches_original(caplog):
    """generate() should produce output matching the .env.platform contract structure."""
    data = {
        "profiles": ["postgres", "redis"],
        "provides": {
            "postgres": {
                "host": "pgbouncer",
                "port": 6432,
                "dsn_template": "postgresql://${NAME}_user:***@pgbouncer:6432/${NAME}_db",
                "networks": ["shared-db-net"],
            },
            "redis": {
                "host": "redis",
                "port": 6379,
                "url_template": "redis://redis:6379/0",
                "networks": ["shared-cache-net"],
            },
        },
        "proxy": {
            "no_proxy_internal": "localhost,127.0.0.1,.local,postgres,pgbouncer,redis,clickhouse",
        },
    }

    lines = gep.generate(data, domain="test.local", project_name="myapp")

    # First line is the header
    assert lines[0] == "# GENERATED by ai-platform — DO NOT EDIT"

    # Contains PLATFORM_DOMAIN
    assert any("PLATFORM_DOMAIN=test.local" in line for line in lines)

    # Contains PLATFORM_PROVIDES
    assert any("PLATFORM_PROVIDES=" in line for line in lines)

    # Contains PLATFORM_*_HOST, PLATFORM_*_PORT, PLATFORM_*_DSN for each service
    assert any("PLATFORM_POSTGRES_HOST=pgbouncer" in line for line in lines)
    assert any("PLATFORM_POSTGRES_PORT=6432" in line for line in lines)
    assert any("PLATFORM_POSTGRES_DSN=postgresql://myapp_user:***@pgbouncer:6432/myapp_db" in line for line in lines)

    assert any("PLATFORM_REDIS_HOST=redis" in line for line in lines)
    assert any("PLATFORM_REDIS_PORT=6379" in line for line in lines)
    assert any("PLATFORM_REDIS_URL=redis://redis:6379/0" in line for line in lines)

    # Contains PLATFORM_NO_PROXY
    assert any("PLATFORM_NO_PROXY=" in line for line in lines)

    # Contains network variables
    assert any("PLATFORM_SHARED_DB_NET=shared-db-net" in line for line in lines)
    assert any("PLATFORM_SHARED_CACHE_NET=shared-cache-net" in line for line in lines)

    logger.critical(
        "[IMP:9][test] generate() produced %d lines with %d PLATFORM_* variables matching contract",
        len(lines),
        sum(1 for line in lines if line.startswith("PLATFORM_")),
    )


