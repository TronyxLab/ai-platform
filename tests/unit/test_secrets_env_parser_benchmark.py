## @purpose — Time secrets_env_parser.parse() with 1000 variables.
##            Assert completion in <50ms (dev) / <100ms (CI gate).

# 🧪 TRAP[TEST] · 2026-07-30 · benchmark/secrets-parser · REGRESSION(086)
# · SCENARIO(1000 var secrets.env → time parse() → assert <50ms dev / <100ms CI)
# · LAST_FAIL(N/A — new benchmark)
# · REMOVE_IF(parse() complexity changes fundamentally or threshold needs adjustment)


@pytest.mark.benchmark
def test_parse_benchmark_1000_vars(
    caplog: pytest.LogCaptureFixture,
    tmp_path: pathlib.Path,
    large_secrets_env_content: str,
) -> None:
    """Benchmark secrets_env_parser.parse() with 1000 variables.

    ## @purpose — Generate secrets.env with 1000 variables, time parse() via
    ##            time.perf_counter(), assert completion within thresholds.
    ##            Development threshold: <50ms. CI gate threshold: <100ms.
    ##            Benchmark timing printed to stdout for CI dashboard.
    ## @io — ⎋ None (assert-based pass/fail)
    ## @complexity — O(N) where N = 1000 lines, expected < 0.05ms/line
    """
    caplog.set_level(logging.INFO)

    from core.internal.shared.secrets_env_parser import parse

    # ── Step 1: Write large secrets.env ──
    env_file = tmp_path / "secrets_benchmark.env"
    env_file.write_text(large_secrets_env_content, encoding="utf-8")

    file_size = env_file.stat().st_size
    logger.info(
        "[IMP:7][benchmark] Created benchmark secrets.env: %d bytes, %d variables expected",
        file_size,
        NUM_VARIABLES,
    )

    # ── Step 2: Warm-up parse (cold cache) ──
    # Run once before timing to warm OS page cache (first parse may be slower)
    _warmup = parse(str(env_file))
    logger.info("[IMP:7][benchmark] Warm-up parse returned %d entries", len(_warmup))

    # ── Step 3: Timed parse ──
    # Use time.perf_counter() for high-precision timing
    start_time = time.perf_counter()
    result = parse(str(env_file))
    end_time = time.perf_counter()

    elapsed_ms = (end_time - start_time) * 1000.0
    elapsed_us = (end_time - start_time) * 1_000_000.0

    # ── Step 4: Verify correctness of parsed data ──
    assert len(result) >= NUM_VARIABLES, f"parse() returned {len(result)} entries, expected >= {NUM_VARIABLES}"

    # Spot-check known values
    assert result.get("VAR_0042") == "", "VAR_0042 should have empty value"
    assert result.get("VAR_0777") == "", "VAR_0777 (export empty) should have empty value"
    assert result.get("VAR_0200") == "значение_200_日本語", "VAR_0200 (i%200==0) unicode value mismatch"
    # VAR_1000 is 1000 % 200 == 0 → unicode value from fixture logic
    assert result.get("VAR_1000") == "значение_1000_日本語", "VAR_1000 (i%200==0) should have unicode value"

    logger.info(
        "[IMP:8][benchmark] Parsed %d entries in %.3f ms (%.1f µs/variable)",
        len(result),
        elapsed_ms,
        elapsed_us / len(result) if result else 0,
    )

    # ── Step 5: Print benchmark output ──
    print(f"\n[BENCHMARK] secrets_env_parser.parse() with {len(result)} variables:")
    print(f"  Elapsed time:    {elapsed_ms:.3f} ms")
    print(f"  Per variable:    {elapsed_us / len(result):.1f} µs")
    print(f"  File size:       {file_size} bytes")
    print(f"  Dev threshold:   < {DEV_THRESHOLD_MS} ms")
    print(f"  CI gate threshold: < {CI_THRESHOLD_MS} ms")
    print(
        f"  Result:          {'PASS' if elapsed_ms < DEV_THRESHOLD_MS else 'WARN' if elapsed_ms < CI_THRESHOLD_MS else 'FAIL'}"
    )

    # ── Step 6: Assert performance threshold ──
    # Development assertion: < 50ms
    assert elapsed_ms < DEV_THRESHOLD_MS, (
        f"parse() benchmark: {elapsed_ms:.2f} ms exceeds development threshold "
        f"({DEV_THRESHOLD_MS} ms). Performance regression in secrets_env_parser detected."
    )

    # CI gate assertion: < 100ms (more lenient for CI runners)
    # Note: CI assertion is a hard fail — CI runners may be slower
    assert elapsed_ms < CI_THRESHOLD_MS, (
        f"parse() benchmark: {elapsed_ms:.2f} ms exceeds CI gate threshold "
        f"({CI_THRESHOLD_MS} ms). Performance regression detected in CI environment."
    )

    logger.info(
        "[IMP:9][benchmark] PASS — parse() completed in %.3f ms (threshold: %.0f ms)",
        elapsed_ms,
        DEV_THRESHOLD_MS,
    )


