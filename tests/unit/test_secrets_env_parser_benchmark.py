import pytest

_PROJECT_ROOT: pathlib.Path = pathlib.Path(__file__).resolve().parent.parent.parent

logger = logging.getLogger(__name__)

# ── Constants ───────────────────────────────────────────────────────────────

# Performance thresholds
DEV_THRESHOLD_MS: float = 50.0  # Development threshold (fast local machine)
CI_THRESHOLD_MS: float = 100.0  # CI gate threshold (accounting for runner variability)
NUM_VARIABLES: int = 1000  # Number of variables to generate

# ── Fixture: generate 1000 variables ───────────────────────────────────────


# region FIXTURE_generate_1000_var_secrets_env


@pytest.fixture
def large_secrets_env_content() -> str:
    """Generate a secrets.env with exactly 1000 variables.

    ## @purpose — Create a large secrets.env that exercises the parser across:
    ##            - 1000 unique keys with varying value formats
    ##            - Every 10th var uses export prefix
    ##            - Every 25th var uses single quotes
    ##            - Every 50th var uses double quotes
    ##            - Every 100th var has an inline comment (#)
    ##            - Every 200th var has unicode value
    ##            - 5 empty-valued vars at known positions
    ##            - Comment lines interspersed
    ## @io — ⎋ str — secrets.env content with 1000+ lines
    ## @complexity — O(N) where N = 1000
    """
    lines: list[str] = []
    lines.append("# Platform secrets — performance benchmark fixture")
    lines.append("# DO NOT EDIT — auto-generated by test suite")
    lines.append("")

    for i in range(1, NUM_VARIABLES + 1):
        key = f"VAR_{i:04d}"

        # Every 100th line: add a comment
        if i % 100 == 0:
            lines.append(f"# Group {i // 100}: variables {i - 99} to {i}")

        # Every 200th var: unicode value
        if i % 200 == 0:
            lines.append(f'{key}="значение_{i}_日本語"')
        # Every 100th var: inline comment in value
        elif i % 100 == 0:
            lines.append(f"export {key}=value_{i}  # inline comment for var {i}")
        # Every 50th var: double-quoted
        elif i % 50 == 0:
            lines.append(f'{key}="double_quoted_value_{i}"')
        # Every 25th var: single-quoted
        elif i % 25 == 0:
            lines.append(f"{key}='single_quoted_value_{i}'")
        # Every 10th var: export prefix
        elif i % 10 == 0:
            lines.append(f"export {key}=export_value_{i}")
        # Special: empty value at position 42
        elif i == 42:
            lines.append(f"{key}=")
        # Special: empty value at position 777
        elif i == 777:
            lines.append(f"export {key}=")
        # Default: unquoted simple value
        else:
            lines.append(f"{key}=value_{i}")

        # Blank line every 50 vars for realism
        if i % 50 == 0:
            lines.append("")

    # Add a trailing comment
    lines.append("")
    lines.append("# End of benchmark secrets.env")

    result = "\n".join(lines) + "\n"
    assert result.count("=") >= NUM_VARIABLES, (
        f"Generated only {result.count('=')} assignments, expected >= {NUM_VARIABLES}"
    )
    return result


# endregion FIXTURE_generate_1000_var_secrets_env


