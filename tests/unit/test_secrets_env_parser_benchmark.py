# region FUNC_test_parse_benchmark_edge_cases

## @purpose — Verify that parse() handles edge cases efficiently even in
##            large files: empty file, only-comments file, single-line file.

# 🧪 TRAP[TEST] · 2026-07-30 · benchmark/secrets-parser · REGRESSION(086)
# · SCENARIO(edge case files → time parse() → assert <10ms)
# · REMOVE_IF(parse() changes edge-case handling fundamentally)


@pytest.mark.benchmark
def test_parse_benchmark_edge_cases(
    caplog: pytest.LogCaptureFixture,
    tmp_path: pathlib.Path,
) -> None:
    """Benchmark parse() on edge-case files (empty, comments-only, single-line).

    ## @purpose — Edge case performance: empty file, comments-only file, and
    ##            single-line file should parse in under 10ms (essentially
    ##            zero-overhead). Detects if edge-case handling introduces O(N)
    ##            overhead on trivial inputs.
    ## @io — ⎋ None (assert-based pass/fail)
    ## @complexity — O(1) — edge cases are constant-size
    """
    caplog.set_level(logging.INFO)

    from core.internal.shared.secrets_env_parser import parse

    # ── Edge case 1: Empty file ──
    empty_file = tmp_path / "empty.env"
    empty_file.write_text("", encoding="utf-8")

    start = time.perf_counter()
    result = parse(str(empty_file))
    elapsed_ms = (time.perf_counter() - start) * 1000.0

    assert result == {}, "Empty file should return empty dict"
    assert elapsed_ms < 10.0, f"Empty file parse took {elapsed_ms:.2f} ms, expected < 10 ms"
    logger.info(
        "[IMP:8][benchmark-edge] Empty file: %.3f ms (threshold: <10 ms)",
        elapsed_ms,
    )

    # ── Edge case 2: Comments-only file ──
    comments_file = tmp_path / "comments_only.env"
    comments_file.write_text(
        "# This is a comment file\n# Another comment\n# Yet another comment\n# With a trailing comment\n",
        encoding="utf-8",
    )

    start = time.perf_counter()
    result = parse(str(comments_file))
    elapsed_ms = (time.perf_counter() - start) * 1000.0

    assert result == {}, "Comments-only file should return empty dict"
    assert elapsed_ms < 10.0, f"Comments-only file parse took {elapsed_ms:.2f} ms, expected < 10 ms"
    logger.info(
        "[IMP:8][benchmark-edge] Comments-only: %.3f ms (threshold: <10 ms)",
        elapsed_ms,
    )

    # ── Edge case 3: Single-line file ──
    single_file = tmp_path / "single.env"
    single_file.write_text("KEY=value\n", encoding="utf-8")

    start = time.perf_counter()
    result = parse(str(single_file))
    elapsed_ms = (time.perf_counter() - start) * 1000.0

    assert result == {"KEY": "value"}, "Single-line file parse mismatch"
    assert elapsed_ms < 10.0, f"Single-line file parse took {elapsed_ms:.2f} ms, expected < 10 ms"
    logger.info(
        "[IMP:8][benchmark-edge] Single-line: %.3f ms (threshold: <10 ms)",
        elapsed_ms,
    )

    logger.info("[IMP:9][benchmark-edge] PASS — all edge cases parsed within threshold")


# endregion FUNC_test_parse_benchmark_edge_cases
