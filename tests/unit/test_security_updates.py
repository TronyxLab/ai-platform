# region Tests: ensure
class TestEnsure:
    """Idempotent ensure: no-op на совпадение, install при отсутствии, drift-перезапись (R5)."""

    @staticmethod
    def _pkg_installed_true(_pkg: str) -> bool:
        return True

    @staticmethod
    def _pkg_install_noop(_pkgs: list[str]) -> None:
        return None

    def test_ensure_creates_configs_and_logs_imp9(self, patch_paths, caplog):
        auto_file, unattended_file = patch_paths
        with caplog.at_level(logging.INFO):
            assert (
                security_updates.ensure(
                    auto_reboot=True,
                    auto_updates_file=str(auto_file),
                    unattended_file=str(unattended_file),
                    pkg_installed_fn=self._pkg_installed_true,
                    install_pkgs_fn=self._pkg_install_noop,
                )
                is True
            )
        assert auto_file.exists()
        assert unattended_file.exists()
        assert auto_file.read_text() == security_updates.desired_auto_upgrades_config()
        assert unattended_file.read_text() == security_updates.desired_unattended_config(auto_reboot=True)
        assert any("[IMP:9]" in r.message for r in caplog.records), "LDD: IMP:9 не найдено"

    def test_ensure_second_run_is_noop_content_stable(self, patch_paths):
        """Инвариант 6: повторный вызов = no-op — содержимое идентично, install не вызывается."""
        auto_file, unattended_file = patch_paths
        install_calls: list = []

        assert (
            security_updates.ensure(
                auto_reboot=True,
                auto_updates_file=str(auto_file),
                unattended_file=str(unattended_file),
                pkg_installed_fn=self._pkg_installed_true,
                install_pkgs_fn=install_calls.append,
            )
            is True
        )
        first_content = auto_file.read_text()
        assert (
            security_updates.ensure(
                auto_reboot=True,
                auto_updates_file=str(auto_file),
                unattended_file=str(unattended_file),
                pkg_installed_fn=self._pkg_installed_true,
                install_pkgs_fn=install_calls.append,
            )
            is True
        )
        assert auto_file.read_text() == first_content
        assert install_calls == [], "повторный ensure не должен ставить пакет"

    def test_ensure_installs_package_when_missing(self, patch_paths):
        auto_file, unattended_file = patch_paths
        installed: list = []
        assert (
            security_updates.ensure(
                auto_reboot=True,
                auto_updates_file=str(auto_file),
                unattended_file=str(unattended_file),
                pkg_installed_fn=lambda _: False,
                install_pkgs_fn=installed.append,
            )
            is True
        )
        assert installed == [[security_updates.SECURITY_PACKAGE]]

    def test_ensure_drift_rewrites_config(self, patch_paths):
        """R5 negative: устаревший/чужой конфиг на диске → перезаписан желаемым."""
        auto_file, unattended_file = patch_paths
        auto_file.write_text('APT::Periodic::Unattended-Upgrade "0";\ngarbage\n')
        assert (
            security_updates.ensure(
                auto_reboot=True,
                auto_updates_file=str(auto_file),
                unattended_file=str(unattended_file),
                pkg_installed_fn=self._pkg_installed_true,
                install_pkgs_fn=self._pkg_install_noop,
            )
            is True
        )
        assert auto_file.read_text() == security_updates.desired_auto_upgrades_config()

    # GUARD-PRESERVE (168): security-updates guard — R5-negative write-error → ensure() False (никогда не raise), единственное покрытие write-fail ветки
    def test_ensure_returns_false_on_write_error(self, patch_paths):
        """R5 negative: запись в read-only директорию → ensure() False (никогда не raise)."""
        auto_file, _ = patch_paths
        ro_dir = auto_file.parent / "read-only"
        ro_dir.mkdir()
        ro_dir.chmod(0o500)
        try:
            assert (
                security_updates.ensure(
                    auto_reboot=True,
                    auto_updates_file=str(ro_dir / "20auto-upgrades"),
                    unattended_file=str(ro_dir / "50unattended-upgrades"),
                    pkg_installed_fn=self._pkg_installed_true,
                    install_pkgs_fn=self._pkg_install_noop,
                )
                is False
            )
        finally:
            ro_dir.chmod(0o700)


