class TestMain:
    """CLI-контракт: exit 0 на успех, 1 на fatal; --auto-reboot false → ветка reboot off."""

    # GUARD-PRESERVE (168): security-updates guard — CLI exit 0 контракт main (fail-fast канон, DI ensure_fn), единственное покрытие success-ветки main
    def test_main_success_exit_0(self):
        assert (
            security_updates.main(
                [],
                ensure_fn=lambda _: True,
                notify_fn=lambda _: None,
            )
            == 0
        )

    def test_main_auto_reboot_false_passes_false(self):
        captured = {}

        def _fake_ensure(auto_reboot):
            captured["auto_reboot"] = auto_reboot
            return True

        assert (
            security_updates.main(
                ["--auto-reboot", "false"],
                ensure_fn=_fake_ensure,
                notify_fn=lambda _: None,
            )
            == 0
        )
        assert captured["auto_reboot"] is False

    def test_main_fatal_exit_1(self, caplog):
        def _boom(auto_reboot):
            msg = "apt repo unavailable"
            raise RuntimeError(msg)

        sent: list = []
        with caplog.at_level(logging.INFO):
            assert (
                security_updates.main(
                    [],
                    ensure_fn=_boom,
                    notify_fn=lambda reason: sent.append(reason) or True,
                )
                == 1
            )
        assert any("[IMP:10]" in r.message for r in caplog.records)
        assert sent, "162 W6-2: failure-путь обязан вызвать telegram-хук"

    def test_main_failure_calls_telegram_notifier(self, caplog):
        """162 W6-2: исключение в ensure → notify_fn вызывается с причиной, exit 1."""

        def _boom(auto_reboot):
            msg = "dpkg lock held"
            raise RuntimeError(msg)

        sent: list = []

        def _fake_send(reason):
            sent.append(reason)

        with caplog.at_level(logging.INFO):
            assert security_updates.main([], ensure_fn=_boom, notify_fn=_fake_send) == 1, (
                "исключение → exit 1 сохраняется"
            )
        assert sent, "OnError → notify_fn обязан вызываться (W6-2)"
        assert "dpkg lock held" in sent[0], "причина провала передаётся в notify_fn"
        logger.critical("[IMP:9][test] main failure → notify_fn с причиной — OK (W6-2)")

    def test_main_ensure_false_calls_telegram_notifier(self, caplog):
        """162 W6-2: ensure() → False (write/apt сбой) тоже не молчит — notify_fn, exit 1."""
        sent: list = []

        def _fake_send(reason):
            sent.append(reason)

        with caplog.at_level(logging.INFO):
            assert security_updates.main([], ensure_fn=lambda _: False, notify_fn=_fake_send) == 1
        assert sent, "ensure False → notify_fn обязан вызываться (W6-2)"
        assert "ensure returned False" in sent[0]
        logger.critical("[IMP:9][test] main ensure False → notify_fn с причиной — OK (W6-2)")

    def test_notify_config_failure_missing_env_non_fatal(self, caplog, monkeypatch):
        """162 W6-2: send_telegram без токена/чата → False (WARN) — хук non-fatal, exit 1 сохраняется."""
        monkeypatch.delenv("TELEGRAM_BOT_TOKEN", raising=False)
        monkeypatch.delenv("TELEGRAM_CHAT_ID", raising=False)
        with caplog.at_level(logging.INFO):
            assert security_updates.main([], ensure_fn=lambda _: False) == 1, "notifier failure не меняет exit-код"
        assert "Failure notification not delivered" in caplog.text
        logger.critical("[IMP:9][test] notifier missing env → WARN, exit 1 сохраняется — OK (W6-2)")


# endregion Tests: main
