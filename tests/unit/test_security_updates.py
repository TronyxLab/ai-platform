# region Tests: desired configs
class TestDesiredConfigs:
    """Content contracts of generated apt configs (S1 читает их в security_posture)."""

    def test_auto_upgrades_config_has_unattended_upgrade_directive(self):
        config = security_updates.desired_auto_upgrades_config()
        assert 'APT::Periodic::Unattended-Upgrade "1";' in config
        assert 'APT::Periodic::Update-Package-Lists "1";' in config
        assert "DO NOT EDIT MANUALLY" in config

    def test_unattended_config_security_only_origins(self):
        """Origins-Pattern — ТОЛЬКО security-источники (D1): -security/esm, НЕ -updates."""
        config = security_updates.desired_unattended_config(auto_reboot=True)
        assert "origin=Ubuntu,archive=${distro_codename}-security" in config
        assert "origin=UbuntuESM,archive=${distro_codename}-infra-security" in config
        assert "updates" not in config.replace("-security", "").replace(
            "Unattended-Upgrade::Automatic-Reboot", ""
        ).replace("Remove-Unused-Dependencies", "").replace(
            "// Generated by ai-platform security_updates.py (DevPlan 134) — DO NOT EDIT MANUALLY", ""
        )
        # Прямая проверка: никакой origin не содержит suite/archive ${distro_codename}-updates
        assert "-updates" not in config
        assert 'Unattended-Upgrade::AutoRemove "true";' in config

    def test_unattended_config_reboot_on_branch(self):
        """D2: auto_reboot=True → Automatic-Reboot true + 04:30 + WithUsers (live-restore)."""
        config = security_updates.desired_unattended_config(auto_reboot=True)
        assert 'Unattended-Upgrade::Automatic-Reboot "true";' in config
        assert 'Unattended-Upgrade::Automatic-Reboot-Time "04:30";' in config
        assert 'Unattended-Upgrade::Automatic-Reboot-WithUsers "true";' in config

    def test_unattended_config_reboot_off_branch(self):
        """D2: auto_reboot=False → reboot false, без WithUsers (SECURITY_AUTO_REBOOT=false)."""
        config = security_updates.desired_unattended_config(auto_reboot=False)
        assert 'Unattended-Upgrade::Automatic-Reboot "false";' in config
        assert "Automatic-Reboot-WithUsers" not in config
        assert "SECURITY_AUTO_REBOOT=false" in config


