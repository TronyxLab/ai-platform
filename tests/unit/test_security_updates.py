# region Tests: ensure
class TestEnsure:
    """Idempotent ensure: no-op на совпадение, install при отсутствии, drift-перезапись (R5)."""

    def test_ensure_creates_configs_and_logs_imp9(self, patch_paths, pkg_installed, caplog):
        auto_file, unattended_file = patch_paths
        with caplog.at_level(logging.INFO):
            assert security_updates.ensure(auto_reboot=True) is True
        assert auto_file.exists()
        assert unattended_file.exists()
        assert auto_file.read_text() == security_updates.desired_auto_upgrades_config()
        assert unattended_file.read_text() == security_updates.desired_unattended_config(True)
        assert any("[IMP:9]" in r.message for r in caplog.records), "LDD: IMP:9 не найдено"

    def test_ensure_second_run_is_noop_content_stable(self, patch_paths, pkg_installed):
        """Инвариант 6: повторный вызов = no-op — содержимое идентично, install не вызывается."""
        auto_file, _ = patch_paths
        install_calls = []

        def _fake_install(pkgs):
            install_calls.append(pkgs)

        import core.internal.bootstrap.security_updates as su

        su.helpers_system.install_apt_packages = _fake_install  # type: ignore[assignment]
        assert su.ensure(auto_reboot=True) is True
        first_content = auto_file.read_text()
        assert su.ensure(auto_reboot=True) is True
        assert auto_file.read_text() == first_content
        assert install_calls == [], "повторный ensure не должен ставить пакет"

    def test_ensure_installs_package_when_missing(self, patch_paths, monkeypatch):
        monkeypatch.setattr(helpers_system, "is_pkg_installed", lambda pkg: False)
        installed = []
        monkeypatch.setattr(helpers_system, "install_apt_packages", lambda pkgs: installed.append(pkgs))
        assert security_updates.ensure(auto_reboot=True) is True
        assert installed == [[security_updates.SECURITY_PACKAGE]]

    def test_ensure_drift_rewrites_config(self, patch_paths, pkg_installed):
        """R5 negative: устаревший/чужой конфиг на диске → перезаписан желаемым."""
        auto_file, _ = patch_paths
        auto_file.write_text('APT::Periodic::Unattended-Upgrade "0";\nlegacy-garbage\n')
        assert security_updates.ensure(auto_reboot=True) is True
        assert auto_file.read_text() == security_updates.desired_auto_upgrades_config()

    def test_ensure_returns_false_on_write_error(self, patch_paths, pkg_installed, monkeypatch):
        def _boom(*args, **kwargs):
            raise OSError("read-only fs")

        monkeypatch.setattr(security_updates, "atomic_write_text", _boom)
        assert security_updates.ensure(auto_reboot=True) is False


# endregion Tests: ensure


# region Tests: main
class TestMain:
    """CLI-контракт: exit 0 на успех, 1 на fatal; --auto-reboot false → ветка reboot off."""

    def test_main_success_exit_0(self, patch_paths, pkg_installed):
        assert security_updates.main([]) == 0

    def test_main_auto_reboot_false_passes_false(self, patch_paths, pkg_installed, monkeypatch):
        captured = {}

        def _fake_ensure(auto_reboot):
            captured["auto_reboot"] = auto_reboot
            return True

        monkeypatch.setattr(security_updates, "ensure", _fake_ensure)
        assert security_updates.main(["--auto-reboot", "false"]) == 0
        assert captured["auto_reboot"] is False

    def test_main_fatal_exit_1(self, patch_paths, pkg_installed, monkeypatch, caplog):
        def _boom(auto_reboot):
            raise RuntimeError("apt repo unavailable")

        monkeypatch.setattr(security_updates, "ensure", _boom)
        with caplog.at_level(logging.INFO):
            assert security_updates.main([]) == 1
        assert any("[IMP:10]" in r.message for r in caplog.records)


# endregion Tests: main
